# Shared AI-attribution patterns for .githooks/commit-msg and .claude/hooks/attribution-gate.sh.
# attribution_hits reads text on stdin, prints matching lines, and returns 0 when any match, 1
# when none, and 2 when the text could not be checked (callers treat 2 as a match).
# A form quoted in backticks (prose about the rule) is ignored.
#
# Keys and tool names match in any case; "AI" matches only as the capitalized word, so names and
# words containing "ai" (Kailash, "Drafted by Vainnor") pass. A "Generated/Drafted with/by" line
# counts only when a tool is named right after it, at the start of a line, after a literal \n in
# a command string, or after a quote or Markdown marker (* _ > -). A tool name followed by a
# hyphen is a different word, so "Generated by codex-path-rules" passes.
attribution_tools='(Claude|Anthropic|ChatGPT|GPT(-[0-9.]+[a-z]*)?|Codex|OpenAI|Copilot)'
attribution_lead='(^|\\n|["'"'"'*_>-])[[:space:]]*(🤖[[:space:]]*)?'
attribution_end='([^-[:alnum:]]|$)'
attribution_pattern="(Co-Authored-By:.*\\b${attribution_tools}\\b)|(${attribution_lead}(Generated|Drafted) (with|by) \\[?${attribution_tools}${attribution_end})|(🤖)|(claude\\.ai/code)|(claude\\.com/claude-code)"
# grep -i would also match "ai", so this pattern is case-sensitive and spells its keys out in
# both cases; git reads trailer keys in any case.
attribution_ci_key='[Cc][Oo]-[Aa][Uu][Tt][Hh][Oo][Rr][Ee][Dd]-[Bb][Yy]:'
attribution_ci_lead_words='([Gg][Ee][Nn][Ee][Rr][Aa][Tt][Ee][Dd]|[Dd][Rr][Aa][Ff][Tt][Ee][Dd]) ([Ww][Ii][Tt][Hh]|[Bb][Yy])'
attribution_pattern_ai="(${attribution_ci_key}.*\\bAI\\b)|(${attribution_lead}${attribution_ci_lead_words} \\[?AI${attribution_end})"

attribution_hits() {
    local text out_tools out_ai status_tools status_ai
    text="$(sed -E 's/`[^`]*`//g')" || { printf 'attribution check failed (sed)\n'; return 2; }
    out_tools="$(grep -inE "$attribution_pattern" <<<"$text")"
    status_tools=$?
    out_ai="$(grep -nE "$attribution_pattern_ai" <<<"$text")"
    status_ai=$?
    if [[ $status_tools -gt 1 || $status_ai -gt 1 ]]; then
        printf 'attribution check failed (exit %s, %s)\n' "$status_tools" "$status_ai"
        return 2
    fi
    if [[ $status_tools -eq 0 || $status_ai -eq 0 ]]; then
        printf '%s\n' "$out_tools" "$out_ai" | grep -v '^$'
        return 0
    fi
    return 1
}
