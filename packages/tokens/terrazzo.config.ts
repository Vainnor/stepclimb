// Builds build/css/variables.css (every theme as CSS variables) and build/css/tailwind-theme.css
// (Tailwind 4's theme mapped onto those variables) from the DTCG tokens in src/tokens/.
import { defineConfig } from "@terrazzo/cli";
import type { Plugin } from "@terrazzo/parser";
import css from "@terrazzo/plugin-css";

/** `color.bg-canvas` -> `sc-bg-canvas`; `radius.sm` -> `sc-radius-sm`. */
function variableName(id: string): string {
  const [group, ...rest] = id.split(".");
  return `sc-${(group === "color" ? rest : [group, ...rest]).join("-")}`;
}

/**
 * Theme selectors. The page's `data-sc-theme` wins over the OS setting (plan, UI tab -> What we
 * borrow: `data-theme`, then `prefers-color-scheme`); the brand comes from `data-sc-brand`.
 */
const wrap = (selectors: string[]) => (contents: string) =>
  `${selectors.join(",\n")} {\n${contents}\n}`;
const media = (selectors: string[]) => (contents: string) =>
  `@media (prefers-color-scheme: dark) {\n  ${selectors.join(",\n  ")} {\n${contents}\n  }\n}`;

/** Theme permutations after the first carry only what changes between themes. */
const themed = ["color.*", "font.ui"];

/** Tailwind's own palette is removed, so `bg-blue-500` does not exist (plan, UI tab -> Tokens). */
function tailwindTheme(): Plugin {
  return {
    name: "stepclimb-tailwind-theme",
    async build({ tokens, outputFile }) {
      const prefixes: Record<string, string> = {
        color: "color",
        radius: "radius",
        text: "text",
        weight: "font-weight",
        font: "font",
        ease: "ease",
        space: "spacing",
      };
      const lines = ["--color-*: initial;"];
      // Tailwind 4 has no duration namespace in @theme, so `duration-fast` (the plan's Button)
      // is a utility of its own per motion token.
      const utilities: string[] = [];
      for (const id of Object.keys(tokens).sort()) {
        const [group, ...rest] = id.split(".");
        if (group === "motion") {
          const name = rest.join("-");
          utilities.push(
            `@utility duration-${name} {\n  transition-duration: var(--${variableName(id)});\n}`,
          );
          continue;
        }
        const prefix = group ? prefixes[group] : undefined;
        if (!prefix) continue;
        // Surfaces drop their `bg-` so the utilities read `bg-canvas`, `bg-raised`, `ring-offset-canvas`.
        const name = group === "color" ? rest.join("-").replace(/^bg-/, "") : rest.join("-");
        lines.push(`--${prefix}-${name}: var(--${variableName(id)});`);
      }
      outputFile(
        "css/tailwind-theme.css",
        `/* Generated by packages/tokens (terrazzo.config.ts). Do not edit. */\n@theme inline {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n\n${utilities.join("\n\n")}\n`,
      );
    },
  };
}

export default defineConfig({
  tokens: ["./src/tokens/resolver.json"],
  outDir: "./build/",
  plugins: [
    css({
      filename: "css/variables.css",
      variableName: (token) => variableName(token.id),
      permutations: [
        { input: { theme: "default-light" }, prepare: wrap([":root", '[data-sc-theme="light"]']) },
        {
          input: { theme: "default-dark" },
          include: themed,
          prepare: wrap(['[data-sc-theme="dark"]']),
        },
        {
          input: { theme: "default-dark" },
          include: themed,
          prepare: media([':root:not([data-sc-theme="light"])']),
        },
        {
          input: { theme: "vzdc-light" },
          include: themed,
          prepare: wrap([
            '[data-sc-brand="vzdc"]',
            '[data-sc-brand="vzdc"][data-sc-theme="light"]',
          ]),
        },
        {
          input: { theme: "vzdc-dark" },
          include: themed,
          prepare: wrap(['[data-sc-brand="vzdc"][data-sc-theme="dark"]']),
        },
        {
          input: { theme: "vzdc-dark" },
          include: themed,
          prepare: media([':root[data-sc-brand="vzdc"]:not([data-sc-theme="light"])']),
        },
      ],
    }),
    tailwindTheme(),
  ],
});
