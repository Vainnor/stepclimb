// The Terrazzo configuration: build/css/variables.css (every theme as CSS variables) and
// build/css/tailwind-theme.css (Tailwind 4's theme mapped onto those variables). It takes the
// resolver path so a test can build a modified copy of the token JSON with the same settings.
import type { Config, Plugin } from "@terrazzo/parser";
import css from "@terrazzo/plugin-css";

/** `color.bg-canvas` -> `--sc-bg-canvas`; `radius.sm` -> `--sc-radius-sm`. */
export function variableName(id: string): string {
  const [group, ...rest] = id.split(".");
  return `--sc-${(group === "color" ? rest : [group, ...rest]).join("-")}`;
}

/**
 * Theme selectors. The page's `data-sc-theme` wins over the OS setting (plan, UI tab -> What we
 * borrow: `data-theme`, then `prefers-color-scheme`); the brand comes from `data-sc-brand`.
 */
const wrap = (selectors: string[]) => (contents: string) =>
  `${selectors.join(",\n")} {\n${contents}\n}`;
const media = (selectors: string[]) => (contents: string) =>
  `@media (prefers-color-scheme: dark) {\n  ${selectors.join(",\n  ")} {\n${contents}\n  }\n}`;

/**
 * The OS dark setting applies only when the page chose neither light nor high contrast; without
 * the second `:not`, this selector's higher specificity would beat `[data-sc-theme="high-contrast"]`.
 */
const osDark = ':not([data-sc-theme="light"]):not([data-sc-theme="high-contrast"])';

/**
 * Theme permutations carry only what changes between themes. Everything else (space, type,
 * control heights) is declared once on `:root`, so a theme attribute on an inner element never
 * resets the density of the view around it.
 */
const themed = ["color.*", "font.ui"];

/**
 * One brand's light, dark (by attribute, then by OS setting) and high-contrast permutations.
 * A brand's selectors compound `data-sc-brand` with `data-sc-theme`, so both attributes must be
 * on the same element; a `data-sc-theme` alone on an inner element selects the default brand.
 */
function brandPermutations(brand: string, attr: string) {
  const light = attr ? [attr, `${attr}[data-sc-theme="light"]`] : ['[data-sc-theme="light"]'];
  return [
    { input: { theme: `${brand}-light` }, include: themed, prepare: wrap(light) },
    {
      input: { theme: `${brand}-dark` },
      include: themed,
      prepare: wrap([`${attr}[data-sc-theme="dark"]`]),
    },
    {
      input: { theme: `${brand}-dark` },
      include: themed,
      prepare: media([`:root${attr}${osDark}`]),
    },
    {
      input: { theme: `${brand}-high-contrast` },
      include: themed,
      prepare: wrap([`${attr}[data-sc-theme="high-contrast"]`]),
    },
  ];
}

/** Tailwind's own palette is removed, so `bg-blue-500` does not exist (plan, UI tab -> Tokens). */
function tailwindTheme(): Plugin {
  return {
    name: "stepclimb-tailwind-theme",
    async build({ tokens, outputFile }) {
      const prefixes: Record<string, string> = {
        color: "color",
        radius: "radius",
        text: "text",
        leading: "leading",
        weight: "font-weight",
        font: "font",
        ease: "ease",
        space: "spacing",
        shadow: "shadow",
      };
      const lines = ["--color-*: initial;"];
      // Tailwind 4 has no duration namespace in @theme, so `duration-fast` (the plan's Button)
      // is a utility of its own per motion token.
      const utilities: string[] = [];
      for (const id of Object.keys(tokens).sort()) {
        const [group, ...rest] = id.split(".");
        if (group === "motion") {
          const name = rest.join("-");
          utilities.push(
            `@utility duration-${name} {\n  transition-duration: var(${variableName(id)});\n}`,
          );
          continue;
        }
        const prefix = group ? prefixes[group] : undefined;
        if (!prefix) continue;
        // Surfaces drop their `bg-` so the utilities read `bg-canvas`, `bg-overlay`, `ring-offset-canvas`.
        const name = group === "color" ? rest.join("-").replace(/^bg-/, "") : rest.join("-");
        lines.push(`--${prefix}-${name}: var(${variableName(id)});`);
      }
      outputFile(
        "css/tailwind-theme.css",
        `/* Generated by packages/tokens (src/config.ts). Do not edit. */\n@theme inline {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n\n${utilities.join("\n\n")}\n`,
      );
    },
  };
}

export function tokensConfig(resolver: string): Config {
  return {
    tokens: [resolver],
    outDir: "./build/",
    plugins: [
      css({
        filename: "css/variables.css",
        variableName: (token) => variableName(token.id),
        permutations: [
          // Every token once, in the default light theme.
          { input: { theme: "default-light" }, prepare: wrap([":root"]) },
          ...brandPermutations("default", ""),
          ...brandPermutations("vzdc", '[data-sc-brand="vzdc"]'),
          // Density is independent of the theme, so a compact view can sit inside any theme.
          {
            input: { theme: "default-light", density: "compact" },
            include: ["control.h", "control.h-sm"],
            prepare: wrap(['[data-sc-density="compact"]']),
          },
        ],
      }),
      tailwindTheme(),
    ],
  };
}
